// Die Rechtstexte liegen wegen ihres Umfangs in einer eigenen Datei, werden
// hier aber in dieselben Woerterbuecher gemischt — fuer t() und applyI18n()
// ist kein Unterschied sichtbar.
const DICTS: Record<UILang, Dict> = {
  de: { ...de, ...LEGAL.de },
  en: { ...en, ...LEGAL.en },
  es: { ...es, ...LEGAL.es },
  fr: { ...fr, ...LEGAL.fr },
  it: { ...it, ...LEGAL.it },
  pt: { ...pt, ...LEGAL.pt },
};

let current: UILang = 'en';

export function setUILang(lang: UILang) {
  current = lang;
}

export function getUILang(): UILang {
  return current;
}

function lookup(key: string): string | string[] {
  return DICTS[current][key] ?? DICTS.en[key] ?? DICTS.de[key] ?? key;
}

export function t(key: string, params?: Record<string, string | number>): string {
  let s = lookup(key);
  if (Array.isArray(s)) s = s.join(' ');
  for (const [k, v] of Object.entries(params ?? {})) {
    s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

export function tList(key: string): string[] {
  const s = lookup(key);
  return Array.isArray(s) ? s : [s];
}

// Uebersetzt alle annotierten Elemente im Dokument (siehe Kopfkommentar).
export function applyI18n() {
  document.documentElement.lang = current;
  document.title = t('meta.title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta.desc'));
  document.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n!);
  });
  document.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml!);
  });
  document.querySelectorAll<HTMLElement>('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr!.split(';')) {
      const idx = pair.indexOf(':');
      if (idx < 0) continue;
      el.setAttribute(pair.slice(0, idx).trim(), t(pair.slice(idx + 1).trim()));
    }
  });
}
